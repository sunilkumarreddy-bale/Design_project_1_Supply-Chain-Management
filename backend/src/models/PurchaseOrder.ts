import { Schema, model, InferSchemaType } from 'mongoose';
import { jsonOptions } from './common';

export const PO_STATUSES = [
  'draft',
  'pending_approval',
  'approved',
  'rejected',
  'confirmed',
  'dispatched',
  'partially_received',
  'received',
  'cancelled',
] as const;
export type POStatus = (typeof PO_STATUSES)[number];
/** Statuses whose outstanding quantities count as "on order". */
export const OPEN_PO_STATUSES: POStatus[] = [
  'pending_approval',
  'approved',
  'confirmed',
  'dispatched',
  'partially_received',
];

const POItemSchema = new Schema(
  {
    product: { type: Schema.Types.ObjectId, ref: 'Product', required: true },
    quantityOrdered: { type: Number, required: true, min: [1, 'Quantity must be at least 1'] },
    quantityReceived: { type: Number, min: 0, default: 0 },
    unitCost: { type: Number, min: 0, default: 0 },
    reorderExplanation: { type: Schema.Types.Mixed, default: null },
  },
  { _id: true },
);

const PurchaseOrderSchema = new Schema(
  {
    poNumber: { type: String, required: true, unique: true },
    supplier: { type: Schema.Types.ObjectId, ref: 'Supplier', required: true },
    warehouse: { type: Schema.Types.ObjectId, ref: 'Warehouse', required: true },
    items: {
      type: [POItemSchema],
      validate: { validator: (v: unknown[]) => v.length > 0, message: 'A purchase order needs at least one line' },
    },
    status: { type: String, enum: PO_STATUSES, default: 'pending_approval' },
    autoGenerated: { type: Boolean, default: false },
    source: { type: String, enum: ['manual', 'auto_reorder', 'recovery_plan'], default: 'manual' },
    recoveryPlan: { type: Schema.Types.ObjectId, ref: 'RecoveryPlan', default: null },
    expectedDeliveryDate: { type: Date, default: null },
    actualDeliveryDate: { type: Date, default: null },
    supplierConfirmedQty: { type: Number, min: 0, default: null },
    supplierConfirmedDate: { type: Date, default: null },
    dispatchInfo: {
      dispatchedAt: { type: Date, default: null },
      carrier: { type: String, default: '' },
      trackingNo: { type: String, default: '' },
      eta: { type: Date, default: null },
    },
    createdBy: { type: Schema.Types.ObjectId, ref: 'User', default: null },
    approvedBy: { type: Schema.Types.ObjectId, ref: 'User', default: null },
    approvedAt: { type: Date, default: null },
    rejectedReason: { type: String, default: '' },
    receivedBy: { type: Schema.Types.ObjectId, ref: 'User', default: null },
    notes: { type: String, default: '' },
    payment: {
      status: { type: String, enum: ['none', 'pending', 'paid'], default: 'none' },
      provider: { type: String, default: '' },
      reference: { type: String, default: '' },
    },
  },
  { timestamps: true, toJSON: jsonOptions, toObject: { virtuals: true } },
);
PurchaseOrderSchema.virtual('totalCost').get(function () {
  const items = (this as unknown as { items?: { quantityOrdered: number; unitCost?: number }[] }).items ?? [];
  return items.reduce((s, i) => s + i.quantityOrdered * (i.unitCost ?? 0), 0);
});
PurchaseOrderSchema.index({ status: 1 });
PurchaseOrderSchema.index({ supplier: 1, status: 1 });
PurchaseOrderSchema.index({ warehouse: 1, status: 1 });
PurchaseOrderSchema.index({ 'items.product': 1 });

export type IPurchaseOrder = InferSchemaType<typeof PurchaseOrderSchema>;
export const PurchaseOrder = model('PurchaseOrder', PurchaseOrderSchema);
