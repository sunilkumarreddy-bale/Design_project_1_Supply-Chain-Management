type PODoc = InstanceType<typeof PurchaseOrder>;

export async function loadPO(id: string) {
  const po = await PurchaseOrder.findById(id);
  if (!po) throw ApiError.notFound('Purchase order not found');
  return po;
}

function requireStatus(po: { status: string; poNumber: string }, allowed: string[], action: string) {
  if (!allowed.includes(po.status)) {
    throw ApiError.conflict(`Cannot ${action} ${po.poNumber}: it is ${po.status.replace(/_/g, ' ')}`);
  }
}

const totalOf = (po: { items: { quantityOrdered: number; unitCost?: number | null }[] }) =>
  po.items.reduce((s, i) => s + i.quantityOrdered * (i.unitCost ?? 0), 0);

async function announcePending(po: PODoc) {
  const supplier = await Supplier.findById(po.supplier).select('name').lean();
  await raiseAlert({
    type: 'po_pending_approval',
    severity: 'info',
    warehouse: po.warehouse,
    purchaseOrder: po._id,
    supplier: po.supplier,
    key: po._id.toHexString(),
    message: `${po.poNumber} for ${supplier?.name ?? 'supplier'} (Rs ${fmt(totalOf(po), 2)}) is waiting for approval`,
  });
  await notifySafe(
    { roles: ['admin'] },
    {
      type: 'po.pending_approval',
      subject: `${po.poNumber} needs approval`,
      body: `${po.autoGenerated ? 'Auto-drafted' : 'New'} purchase order for ${supplier?.name ?? 'a supplier'}, ${po.items.length} line(s), Rs ${fmt(
        totalOf(po),
        2,
      )}`,
      link: `/purchase-orders?focus=${po._id}`,
    },
  );
}

export interface ManualPOInput {
  supplier: string;
  warehouse: string;
  items: { product: string; quantityOrdered: number; unitCost?: number | null }[];
  expectedDeliveryDate?: Date | null;
  notes?: string;
  draft?: boolean;
}

export async function createManualPO(input: ManualPOInput, user: AuthUser) {
  assertWarehouseScope(user, input.warehouse);
  const supplier = await Supplier.findById(input.supplier);
  if (!supplier) throw ApiError.notFound('Supplier not found');
  if (supplier.status === 'inactive' || !supplier.isActive) throw ApiError.badRequest(`${supplier.name} is inactive`);
  await requireActiveWarehouse(input.warehouse);
  const seen = new Set<string>();
  const items = [];
  for (const it of input.items) {
    if (seen.has(it.product)) throw ApiError.badRequest('Each product can appear only once per purchase order');
    seen.add(it.product);
    const p = await requireActiveProduct(it.product);
    items.push({ product: p._id, quantityOrdered: it.quantityOrdered, unitCost: it.unitCost ?? p.unitCost, quantityReceived: 0 });
  }
  const po = await PurchaseOrder.create({
    poNumber: await nextPoNumber(),
    supplier: supplier._id,
    warehouse: input.warehouse,
    items,
    status: input.draft ? 'draft' : 'pending_approval',
    source: 'manual',
    expectedDeliveryDate: input.expectedDeliveryDate ?? null,
    notes: input.notes ?? '',
    createdBy: user._id,
  });
  await recordAudit({ action: 'po.create', entityType: 'PurchaseOrder', entityId: po._id, actor: user, warehouse: po.warehouse, after: po });
  emitAll('po:created', po.toJSON());
  if (po.status === 'pending_approval') await announcePending(po);
  return po;
}

export async function submitDraftPO(id: string, user: AuthUser) {
  const po = await loadPO(id);
  requireStatus(po, ['draft'], 'submit');
  assertWarehouseScope(user, po.warehouse);
  const before = snapshot(po);
  po.status = 'pending_approval';
  await po.save();
  await recordAudit({ action: 'po.submit', entityType: 'PurchaseOrder', entityId: po._id, actor: user, warehouse: po.warehouse, before, after: po });
  emitAll('po:created', po.toJSON());
  await announcePending(po);
  return po;
}

export interface AutoDraftResult {
  warehouse: { _id: string; code: string; name: string };
  evaluated: number;
  created: unknown[];
  avoidedByTransfer: {
    product: { _id: string; sku: string; name: string };
    deficit: number;
    reorderPoint: number;
    position: number;
    transfers: { from: { _id: string; code: string; name: string }; to: { _id: string; code: string; name: string }; quantity: number }[];
    explanation: string;
  }[];
  skipped: { product: { _id: string; sku: string; name: string }; reason: string; suggestion?: string }[];
}

/**
 * Auto-draft (3.3): for every active product that should be reordered at the warehouse (position-based, so a
 * second run is a no-op), prefer a transfer of surplus from another warehouse (F4), otherwise draft a PO line
 * of k x EOQ with the full F1 explanation, grouped into one PO per primary supplier.
 */
export async function autoDraft(warehouseId: string, user: AuthUser): Promise<AutoDraftResult> {
  assertWarehouseScope(user, warehouseId);
  const wh = await requireActiveWarehouse(warehouseId);
  const allWh = await Warehouse.find({ isActive: true }).select('code name').lean();
  const names = new Map(allWh.map((w) => [w._id.toHexString(), { code: w.code, name: w.name }]));
  const ref = (id: string) => ({ _id: id, ...names.get(id)! });
  const products = await loadPlanningProducts();
  const ids = products.map((p) => p._id);
  const [oh, oo, dm] = await Promise.all([onHandMap(ids, [warehouseId]), onOrderMap(ids, [warehouseId]), demandMap(products, [warehouseId])]);

  const result: AutoDraftResult = {
    warehouse: { _id: warehouseId, code: wh.code, name: wh.name },
    evaluated: products.length,
    created: [],
    avoidedByTransfer: [],
    skipped: [],
  };
  const bySupplier = new Map<string, { supplier: NonNullable<PlanningProduct['primarySupplier']>; lines: { product: PlanningProduct; qty: number; explanation: unknown; leadDays: number }[] }>();

  for (const p of products) {
    const key = posKey(warehouseId, p._id);
    const onHand = oh.get(key) ?? 0;
    const onOrder = oo.get(key) ?? 0;
    const demand = dm.get(key)!;
    let e = explainWith(p, onHand, onOrder, demand);
    if (!e.shouldReorder) continue;
    const pref = { _id: p._id.toHexString(), sku: p.sku, name: p.name };

    // F4: rebalance before you buy
    const { result: rb } = await rebalanceForProduct(p, names);
    const need = rb?.needs.find((n) => n.warehouse === warehouseId);
    const inbound = rb?.transfers.filter((t) => t.to === warehouseId) ?? [];
    const covered = need?.covered ?? 0;
    if (need && inbound.length && need.uncovered === 0) {
      result.avoidedByTransfer.push({
        product: pref,
        deficit: need.deficit,
        reorderPoint: e.policy.reorderPoint,
        position: e.position,
        transfers: inbound.map((t) => ({ from: ref(t.from), to: ref(t.to), quantity: t.quantity })),
        explanation: `Position ${fmt(e.position)} <= reorder point ${e.policy.reorderPoint}; surplus elsewhere covers the deficit of ${need.deficit}, so no purchase is needed`,
      });
      continue;
    }

    const supplier = p.primarySupplier;
    if (!supplier) {
      result.skipped.push({ product: pref, reason: 'No primary supplier is set for this product' });
      continue;
    }
    if (supplier.status === 'disrupted') {
      result.skipped.push({
        product: pref,
        reason: `Primary supplier ${supplier.name} is disrupted${supplier.disruption ? ` (${supplier.disruption.reason || 'no reason given'}, about ${supplier.disruption.expectedDays} days)` : ''}`,
        suggestion: 'Run the recovery engine to compare transfers and alternative suppliers',
      });
      continue;
    }
    if (supplier.status === 'inactive') {
      result.skipped.push({ product: pref, reason: `Primary supplier ${supplier.name} is inactive` });
      continue;
    }
    if (covered > 0) {
      // part of the deficit can come from surplus elsewhere: buy only for what remains
      e = explainWith(p, onHand, onOrder + covered, demand);
      e.steps.push(
        `Suggested transfers of ${covered} unit(s) (${inbound.map((t) => `${t.quantity} from ${names.get(t.from)!.name}`).join(', ')}) are counted in the position, which reduces this order`,
      );
      if (!e.shouldReorder) continue;
      result.avoidedByTransfer.push({
        product: pref,
        deficit: need!.deficit,
        reorderPoint: e.policy.reorderPoint,
        position: e.position - covered,
        transfers: inbound.map((t) => ({ from: ref(t.from), to: ref(t.to), quantity: t.quantity })),
        explanation: `Transfers cover ${covered} of the ${need!.deficit}-unit deficit; a purchase is drafted for the rest`,
      });
    }
    const sid = supplier._id.toHexString();
    if (!bySupplier.has(sid)) bySupplier.set(sid, { supplier, lines: [] });
    bySupplier.get(sid)!.lines.push({ product: p, qty: e.orderQuantity, explanation: e, leadDays: e.inputs.leadDays });
  }

  for (const { supplier, lines } of bySupplier.values()) {
    const leadDays = Math.max(...lines.map((l) => l.leadDays));
    const po = await PurchaseOrder.create({
      poNumber: await nextPoNumber(),
      supplier: supplier._id,
      warehouse: warehouseId,
      items: lines.map((l) => ({
        product: l.product._id,
        quantityOrdered: l.qty,
        quantityReceived: 0,
        unitCost: l.product.unitCost,
        reorderExplanation: l.explanation,
      })),
      status: 'pending_approval',
      autoGenerated: true,
      source: 'auto_reorder',
      expectedDeliveryDate: addDays(new Date(), Math.ceil(leadDays)),
      createdBy: user._id,
      notes: `Auto-drafted from reorder points for ${wh.name}`,
    });
    await recordAudit({
      action: 'po.auto_draft',
      entityType: 'PurchaseOrder',
      entityId: po._id,
      actor: user,
      warehouse: warehouseId,
      after: po,
      metadata: { lines: lines.length },
    });
    emitAll('po:created', po.toJSON());
    await announcePending(po);
    for (const l of lines) await evaluateStockAlerts(l.product._id, warehouseId);
    result.created.push(po.toJSON());
  }
  return result;
}

export async function approvePO(id: string, user: AuthUser) {
  const po = await loadPO(id);
  requireStatus(po, ['pending_approval'], 'approve');
  const supplier = await Supplier.findById(po.supplier);
  const before = snapshot(po);
  po.status = 'approved';
  po.approvedBy = user._id;
  po.approvedAt = new Date();
  if (!po.expectedDeliveryDate && supplier) {
    const lt = supplierLeadTimeStats(supplier.leadTimeDays, supplier as unknown as Parameters<typeof supplierLeadTimeStats>[1]);
    po.expectedDeliveryDate = addDays(new Date(), Math.ceil(lt.mean));
  }
  await po.save();
  await recordAudit({ action: 'po.approve', entityType: 'PurchaseOrder', entityId: po._id, actor: user, warehouse: po.warehouse, before, after: po });
  await resolveAlerts({ type: 'po_pending_approval', key: po._id.toHexString() }, user._id);
  emitAll('po:approved', po.toJSON());
  await notifySupplierOfApproval(po, supplier);
  await notifySafe(
    { userIds: [po.createdBy] },
    { type: 'po.approved', subject: `${po.poNumber} approved`, body: `Approved by ${user.name}`, link: `/purchase-orders?focus=${po._id}` },
  );
  return po;
}

export async function notifySupplierOfApproval(po: PODoc, supplier: InstanceType<typeof Supplier> | null) {
  if (!supplier) return;
  const msg = {
    type: 'po.approved',
    subject: `Purchase order ${po.poNumber} approved`,
    body: `Please confirm ${po.poNumber}: ${po.items.length} line(s), Rs ${fmt(totalOf(po), 2)}${
      po.expectedDeliveryDate ? `, needed by ${po.expectedDeliveryDate.toISOString().slice(0, 10)}` : ''
    }.`,
    link: `/purchase-orders?focus=${po._id}`,
  };
  await notifySafe({ roles: ['supplier'], supplier: supplier._id }, msg);
  notifyContact({ email: supplier.email, phone: supplier.phone }, msg);
}

export async function rejectPO(id: string, reason: string, user: AuthUser) {
  const po = await loadPO(id);
  requireStatus(po, ['pending_approval', 'draft'], 'reject');
  const before = snapshot(po);
  po.status = 'rejected';
  po.rejectedReason = reason;
  await po.save();
  await recordAudit({ action: 'po.reject', entityType: 'PurchaseOrder', entityId: po._id, actor: user, warehouse: po.warehouse, before, after: po });
  await resolveAlerts({ type: 'po_pending_approval', key: po._id.toHexString() }, user._id);
  emitAll('po:rejected', po.toJSON());
  await notifySafe(
    { userIds: [po.createdBy] },
    { type: 'po.rejected', subject: `${po.poNumber} rejected`, body: reason, link: `/purchase-orders?focus=${po._id}` },
  );
  if (po.recoveryPlan) await updateRecoveryProgress(po.recoveryPlan, { event: 'po_rejected', detail: `${po.poNumber} rejected: ${reason}`, by: user._id });
  for (const it of po.items) await evaluateStockAlerts(it.product, po.warehouse);
  return po;
}

async function notifyWarehouse(po: PODoc, type: string, subject: string, body: string) {
  await notifySafe({ roles: ['admin', 'warehouse_manager'], warehouse: po.warehouse }, { type, subject, body, link: `/purchase-orders?focus=${po._id}` });
}

export async function confirmPO(id: string, input: { confirmedQty: number; confirmedDate: Date }, user: AuthUser) {
  const po = await loadPO(id);
  assertOwnSupplier(user, po.supplier);
  requireStatus(po, ['approved'], 'confirm');
  const before = snapshot(po);
  po.status = 'confirmed';
  po.supplierConfirmedQty = input.confirmedQty;
  po.supplierConfirmedDate = input.confirmedDate;
  po.expectedDeliveryDate = input.confirmedDate;
  await po.save();
  await recordAudit({ action: 'po.confirm', entityType: 'PurchaseOrder', entityId: po._id, actor: user, warehouse: po.warehouse, before, after: po });
  emitAll('po:confirmed', po.toJSON());
  const ordered = po.items.reduce((s, i) => s + i.quantityOrdered, 0);
  await notifyWarehouse(
    po,
    'po.confirmed',
    `${po.poNumber} confirmed by supplier`,
    `Confirmed ${input.confirmedQty} of ${ordered} units for ${input.confirmedDate.toISOString().slice(0, 10)}`,
  );
  if (po.recoveryPlan) await updateRecoveryProgress(po.recoveryPlan, { event: 'po_confirmed', detail: `${po.poNumber} confirmed by the supplier`, by: user._id });
  return po;
}

export async function dispatchPO(id: string, input: { carrier: string; trackingNo: string; eta: Date | null }, user: AuthUser) {
  const po = await loadPO(id);
  assertOwnSupplier(user, po.supplier);
  requireStatus(po, ['approved', 'confirmed'], 'dispatch');
  const before = snapshot(po);
  po.status = 'dispatched';
  po.dispatchInfo = { dispatchedAt: new Date(), carrier: input.carrier, trackingNo: input.trackingNo, eta: input.eta };
  if (input.eta) po.expectedDeliveryDate = input.eta;
  await po.save();
  await recordAudit({ action: 'po.dispatch', entityType: 'PurchaseOrder', entityId: po._id, actor: user, warehouse: po.warehouse, before, after: po });
  emitAll('po:dispatched', po.toJSON());
  await notifyWarehouse(
    po,
    'po.dispatched',
    `${po.poNumber} dispatched`,
    `Carrier ${input.carrier || '-'}, tracking ${input.trackingNo || '-'}${input.eta ? `, ETA ${input.eta.toISOString().slice(0, 10)}` : ''}`,
  );
  if (po.recoveryPlan) await updateRecoveryProgress(po.recoveryPlan, { event: 'po_dispatched', detail: `${po.poNumber} dispatched by the supplier`, by: user._id });
  return po;
}

export interface ReceiveItemInput {
  product: string;
  quantityReceived: number;
  batchNo?: string | null;
  expiryDate?: Date | null;
  bin?: string | null;
}

export async function receivePO(id: string, input: { receivedItems: ReceiveItemInput[]; logDiscrepancy?: boolean; notes?: string }, user: AuthUser) {
  const pre = await loadPO(id);
  requireStatus(pre, ['approved', 'confirmed', 'dispatched', 'partially_received'], 'receive');
  assertWarehouseScope(user, pre.warehouse);
  const before = snapshot(pre);
  const now = new Date();

  const out = await withTransaction(async (session) => {
    const po = await PurchaseOrder.findById(id).session(session);
    if (!po) throw ApiError.notFound('Purchase order not found');
    const wh = await requireActiveWarehouse(po.warehouse, session);
    const shortLines: { product: string; outstanding: number; received: number }[] = [];
    for (const r of input.receivedItems) {
      const item = po.items.find((i) => idStr(i.product) === r.product);
      if (!item) throw ApiError.badRequest(`Product ${r.product} is not on ${po.poNumber}`);
      const outstanding = item.quantityOrdered - item.quantityReceived;
      if (r.quantityReceived > outstanding) {
        throw ApiError.badRequest(`Cannot receive ${r.quantityReceived}: only ${outstanding} outstanding on this line`);
      }
      if (r.quantityReceived <= 0) {
        if (outstanding > 0) shortLines.push({ product: r.product, outstanding, received: 0 });
        continue;
      }
      const product = await requireActiveProduct(r.product, session);
      if (product.isPerishable && !r.expiryDate) throw ApiError.badRequest(`${product.sku} is perishable: an expiry date is required`);
      await addToLine(
        {
          product: product._id,
          warehouse: wh._id,
          bin: resolveBin(wh, r.bin),
          batchNo: (r.batchNo ?? '').trim() || po.poNumber,
          expiryDate: r.expiryDate ?? null,
          quantity: r.quantityReceived,
        },
        session,
      );
      item.quantityReceived += r.quantityReceived;
      if (r.quantityReceived < outstanding) shortLines.push({ product: r.product, outstanding, received: r.quantityReceived });
    }
    const fully = po.items.every((i) => i.quantityReceived >= i.quantityOrdered);
    po.status = fully ? 'received' : 'partially_received';
    po.receivedBy = user._id;
    if (input.notes) po.notes = [po.notes, input.notes].filter(Boolean).join('\n');
    let leadTimeSample: { days: number; onTime: boolean } | null = null;
    if (fully) {
      po.actualDeliveryDate = now;
      const supplier = await Supplier.findById(po.supplier).session(session);
      if (supplier) {
        const start = po.approvedAt ?? (po as unknown as { createdAt: Date }).createdAt;
        const days = Math.max(1, Math.round((now.getTime() - new Date(start).getTime()) / DAY_MS));
        const deadline = po.expectedDeliveryDate ? new Date(po.expectedDeliveryDate).getTime() + DAY_MS : null;
        const onTime = deadline !== null ? now.getTime() <= deadline : days <= supplier.leadTimeDays;
        const acc = applyLeadTimeSample(
          { leadTimeSamples: supplier.leadTimeSamples, leadTimeSum: supplier.leadTimeSum, leadTimeSumSq: supplier.leadTimeSumSq },
          days,
        );
        supplier.leadTimeSamples = acc.leadTimeSamples;
        supplier.leadTimeSum = acc.leadTimeSum;
        supplier.leadTimeSumSq = acc.leadTimeSumSq;
        supplier.totalOrders += 1;
        if (onTime) supplier.onTimeDeliveries += 1;
        else supplier.lateDeliveries += 1;
        supplier.performanceScore = supplierPerformanceScore(supplier.onTimeDeliveries, supplier.lateDeliveries);
        await supplier.save({ session });
        leadTimeSample = { days, onTime };
      }
    }
    await po.save({ session });
    const discrepancies = [];
    if (input.logDiscrepancy) {
      for (const s of shortLines) {
        const [d] = await Discrepancy.create(
          [
            {
              type: 'receipt_mismatch',
              purchaseOrder: po._id,
              product: s.product,
              warehouse: po.warehouse,
              expectedQty: s.outstanding,
              actualQty: s.received,
              notes: `Received ${s.received} of ${s.outstanding} outstanding on ${po.poNumber}`,
              createdBy: user._id,
            },
          ],
          { session },
        );
        discrepancies.push(d);
      }
    }
    return { po, shortLines, discrepancies, leadTimeSample };
  });

  const { po } = out;
  await recordAudit({
    action: 'po.receive',
    entityType: 'PurchaseOrder',
    entityId: po._id,
    actor: user,
    warehouse: po.warehouse,
    before,
    after: po,
    metadata: { receivedItems: input.receivedItems, leadTimeSample: out.leadTimeSample },
  });
  if (out.leadTimeSample) {
    await recordAudit({
      action: 'supplier.lead_time_sample',
      entityType: 'Supplier',
      entityId: po.supplier,
      actor: user,
      after: out.leadTimeSample,
      metadata: { poNumber: po.poNumber },
    });
  }
  for (const d of out.discrepancies) {
    await recordAudit({ action: 'discrepancy.create', entityType: 'Discrepancy', entityId: d._id, actor: user, warehouse: po.warehouse, after: d });
    await raiseAlert({
      type: 'discrepancy',
      severity: 'warning',
      product: d.product,
      warehouse: d.warehouse,
      purchaseOrder: po._id,
      key: d._id.toHexString(),
      message: `${po.poNumber}: received ${d.actualQty} of ${d.expectedQty} expected units`,
    });
  }
  if (po.status === 'received') await resolveAlerts({ type: 'po_overdue', key: po._id.toHexString() }, user._id);
  emitAll('po:received', po.toJSON());
  for (const it of input.receivedItems) {
    if (it.quantityReceived > 0) await afterStockChange(it.product, [po.warehouse], { action: 'po_receive', quantity: it.quantityReceived });
  }
  if (po.recoveryPlan) {
    await updateRecoveryProgress(po.recoveryPlan, {
      event: po.status === 'received' ? 'po_received' : 'po_partially_received',
      detail: `${po.poNumber} ${po.status === 'received' ? 'fully received' : 'partially received'}`,
      by: user._id,
    });
  }
  return { purchaseOrder: po, shortLines: out.shortLines, discrepancies: out.discrepancies, leadTimeSample: out.leadTimeSample };
}

export async function cancelPO(id: string, user: AuthUser) {
  const po = await loadPO(id);
  requireStatus(po, ['draft', 'pending_approval', 'approved', 'confirmed', 'dispatched'], 'cancel');
  const before = snapshot(po);
  po.status = 'cancelled';
  await po.save();
  await recordAudit({ action: 'po.cancel', entityType: 'PurchaseOrder', entityId: po._id, actor: user, warehouse: po.warehouse, before, after: po });
  await resolveAlerts({ purchaseOrder: po._id, type: { $in: ['po_pending_approval', 'po_overdue'] } }, user._id);
  emitAll('po:cancelled', po.toJSON());
  if (po.recoveryPlan) await updateRecoveryProgress(po.recoveryPlan, { event: 'po_cancelled', detail: `${po.poNumber} cancelled`, by: user._id });
  for (const it of po.items) await evaluateStockAlerts(it.product, po.warehouse);
  return po;
}

export async function payPO(id: string, user: AuthUser) {
  if (!paymentsEnabled()) throw ApiError.forbidden('Payments are disabled (set ENABLE_PAYMENTS=true)');
  const po = await loadPO(id);
  requireStatus(po, ['approved', 'confirmed', 'dispatched', 'partially_received', 'received'], 'pay');
  if (po.payment?.status && po.payment.status !== 'none') throw ApiError.conflict(`${po.poNumber} already has a ${po.payment.status} payment`);
  const before = snapshot(po);
  const r = await getPaymentsDriver().createOrder({ amountInr: totalOf(po), receipt: po.poNumber, description: `Payment for ${po.poNumber}` });
  po.payment = { status: r.status, provider: r.provider, reference: r.reference };
  await po.save();
  await recordAudit({ action: 'po.pay', entityType: 'PurchaseOrder', entityId: po._id, actor: user, warehouse: po.warehouse, before, after: po });
  emitAll('po:paid', po.toJSON());
  return po;
}

