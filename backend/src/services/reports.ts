/** CSV and PDF reports. PDFs use the built-in Helvetica font, so amounts are written as "Rs" (no rupee glyph). */
import PDFDocument from 'pdfkit';
import { PurchaseOrder, StockLevel, Supplier } from '../models';
import { supplierLeadTimeStats } from '../engines/reorder';
import { toCsv } from '../utils/csv';
import { expiryRiskFor, loadPlanningProducts } from './planning';

const d10 = (d: Date | null | undefined) => (d ? new Date(d).toISOString().slice(0, 10) : '');
const money = (n: number) => `Rs ${n.toLocaleString('en-IN', { maximumFractionDigits: 2 })}`;

async function stockRows(warehouse?: string | null) {
  const lines = await StockLevel.find({ quantity: { $gt: 0 }, ...(warehouse ? { warehouse } : {}) })
    .populate('product', 'sku name unitCost unit')
    .populate('warehouse', 'code name')
    .lean();
  return lines
    .map((l) => {
      const p = l.product as unknown as { sku: string; name: string; unitCost: number; unit: string } | null;
      const w = l.warehouse as unknown as { code: string; name: string } | null;
      return {
        sku: p?.sku ?? '',
        product: p?.name ?? '',
        unit: p?.unit ?? '',
        warehouse: w?.code ?? '',
        bin: l.bin,
        batchNo: l.batchNo,
        expiry: d10(l.expiryDate),
        quantity: l.quantity,
        unitCost: p?.unitCost ?? 0,
        value: l.quantity * (p?.unitCost ?? 0),
        reorderPoint: l.reorderPoint,
      };
    })
    .sort((a, b) => a.sku.localeCompare(b.sku) || a.warehouse.localeCompare(b.warehouse));
}

export async function stockCsv(warehouse?: string | null) {
  const rows = await stockRows(warehouse);
  return toCsv(
    ['SKU', 'Product', 'Unit', 'Warehouse', 'Bin', 'Batch', 'Expiry', 'Quantity', 'Unit cost (INR)', 'Value (INR)', 'Reorder point'],
    rows.map((r) => [r.sku, r.product, r.unit, r.warehouse, r.bin, r.batchNo, r.expiry, r.quantity, r.unitCost, r.value, r.reorderPoint]),
  );
}

async function poRows(filter: Record<string, unknown> = {}) {
  const pos = await PurchaseOrder.find(filter)
    .populate('supplier', 'name')
    .populate('warehouse', 'code')
    .sort({ createdAt: -1 })
    .lean({ virtuals: true });
  return pos.map((po) => ({
    poNumber: po.poNumber,
    supplier: (po.supplier as unknown as { name: string } | null)?.name ?? '',
    warehouse: (po.warehouse as unknown as { code: string } | null)?.code ?? '',
    status: po.status,
    source: po.source,
    auto: po.autoGenerated ? 'yes' : 'no',
    lines: po.items.length,
    units: po.items.reduce((s, i) => s + i.quantityOrdered, 0),
    received: po.items.reduce((s, i) => s + i.quantityReceived, 0),
    total: po.items.reduce((s, i) => s + i.quantityOrdered * (i.unitCost ?? 0), 0),
    expected: d10(po.expectedDeliveryDate),
    created: d10((po as unknown as { createdAt: Date }).createdAt),
    approved: d10(po.approvedAt),
    delivered: d10(po.actualDeliveryDate),
  }));
}

export async function purchaseOrdersCsv(filter: Record<string, unknown> = {}) {
  const rows = await poRows(filter);
  return toCsv(
    ['PO number', 'Supplier', 'Warehouse', 'Status', 'Source', 'Auto', 'Lines', 'Units ordered', 'Units received', 'Total (INR)', 'Expected', 'Created', 'Approved', 'Delivered'],
    rows.map((r) => [r.poNumber, r.supplier, r.warehouse, r.status, r.source, r.auto, r.lines, r.units, r.received, r.total, r.expected, r.created, r.approved, r.delivered]),
  );
}

async function supplierRows(filter: Record<string, unknown> = {}) {
  const suppliers = await Supplier.find(filter).sort({ name: 1 }).lean();
  return suppliers.map((s) => {
    const lt = supplierLeadTimeStats(s.leadTimeDays, s);
    return {
      _id: s._id.toHexString(),
      name: s.name,
      contact: s.contactName,
      email: s.email,
      phone: s.phone,
      promised: s.leadTimeDays,
      learned: Math.round(lt.mean * 100) / 100,
      observedMean: lt.observedMean === null ? null : Math.round(lt.observedMean * 100) / 100,
      std: Math.round(lt.std * 100) / 100,
      samples: lt.samples,
      source: lt.source,
      onTime: s.onTimeDeliveries,
      late: s.lateDeliveries,
      total: s.totalOrders,
      score: s.performanceScore,
      status: s.status,
    };
  });
}

export async function suppliersCsv() {
  const rows = await supplierRows();
  return toCsv(
    ['Supplier', 'Contact', 'Email', 'Phone', 'Promised lead time (days)', 'Learned lead time (days)', 'Lead time std dev', 'Samples', 'On-time', 'Late', 'Total orders', 'Score', 'Status'],
    rows.map((r) => [r.name, r.contact, r.email, r.phone, r.promised, r.learned, r.std, r.samples, r.onTime, r.late, r.total, r.score, r.status]),
  );
}

export async function expiryCsv(warehouse?: string | null) {
  const products = await loadPlanningProducts();
  const rows = await expiryRiskFor(products, warehouse ?? null);
  return toCsv(
    ['SKU', 'Product', 'Warehouse', 'Batch', 'Bin', 'Expiry', 'Days left', 'Units', 'Daily demand', 'Projected waste', 'Value at risk (INR)'],
    rows.map((r) => [
      r.product.sku,
      r.product.name,
      r.warehouse.code,
      r.batchNo,
      r.bin,
      d10(r.expiryDate),
      r.daysLeft,
      r.units,
      Math.round(r.dailyDemand * 100) / 100,
      r.projectedWaste,
      r.valueAtRisk,
    ]),
  );
}

/* ------------------------------------------------------------------ PDF */

interface Column {
  header: string;
  width: number;
  align?: 'left' | 'right';
}

function pdfBuffer(build: (doc: PDFKit.PDFDocument) => void): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', layout: 'landscape', margin: 36, info: { Title: 'Smart Inventory report' } });
    const chunks: Buffer[] = [];
    doc.on('data', (c: Buffer) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    build(doc);
    doc.end();
  });
}

function header(doc: PDFKit.PDFDocument, title: string, subtitle: string) {
  doc.fillColor('#8c1d2f').fontSize(18).font('Helvetica-Bold').text(title);
  doc.fillColor('#555').fontSize(9).font('Helvetica').text(subtitle);
  doc.moveDown(0.8);
}

function table(doc: PDFKit.PDFDocument, cols: Column[], rows: (string | number)[][]) {
  const x0 = doc.page.margins.left;
  const bottom = doc.page.height - doc.page.margins.bottom;
  const drawHeader = () => {
    let x = x0;
    doc.font('Helvetica-Bold').fontSize(8).fillColor('#ffffff');
    const y = doc.y;
    doc.rect(x0, y - 2, cols.reduce((s, c) => s + c.width, 0), 14).fill('#26365b');
    doc.fillColor('#ffffff');
    for (const c of cols) {
      doc.text(c.header, x + 3, y + 1, { width: c.width - 6, align: c.align ?? 'left', lineBreak: false });
      x += c.width;
    }
    doc.y = y + 14;
  };
  drawHeader();
  doc.font('Helvetica').fontSize(8).fillColor('#222');
  rows.forEach((r, i) => {
    if (doc.y + 13 > bottom) {
      doc.addPage();
      drawHeader();
      doc.font('Helvetica').fontSize(8).fillColor('#222');
    }
    const y = doc.y;
    if (i % 2 === 1) doc.rect(x0, y - 1, cols.reduce((s, c) => s + c.width, 0), 13).fill('#f3efe8');
    doc.fillColor('#222');
    let x = x0;
    cols.forEach((c, j) => {
      doc.text(String(r[j] ?? ''), x + 3, y + 1, { width: c.width - 6, align: c.align ?? 'left', lineBreak: false, ellipsis: true });
      x += c.width;
    });
    doc.y = y + 13;
  });
  if (!rows.length) doc.text('No data.', x0, doc.y + 4);
}

export async function stockPdf(warehouse?: string | null) {
  const rows = await stockRows(warehouse);
  const total = rows.reduce((s, r) => s + r.value, 0);
  return pdfBuffer((doc) => {
    header(doc, 'Stock report', `Generated ${new Date().toISOString().slice(0, 16).replace('T', ' ')} UTC - ${rows.length} lines - value ${money(total)}`);
    table(
      doc,
      [
        { header: 'SKU', width: 85 },
        { header: 'Product', width: 160 },
        { header: 'Warehouse', width: 70 },
        { header: 'Bin', width: 45 },
        { header: 'Batch', width: 90 },
        { header: 'Expiry', width: 65 },
        { header: 'Qty', width: 55, align: 'right' },
        { header: 'Unit cost', width: 70, align: 'right' },
        { header: 'Value', width: 80, align: 'right' },
        { header: 'ROP', width: 50, align: 'right' },
      ],
      rows.map((r) => [r.sku, r.product, r.warehouse, r.bin, r.batchNo, r.expiry, r.quantity, money(r.unitCost), money(r.value), r.reorderPoint]),
    );
  });
}

