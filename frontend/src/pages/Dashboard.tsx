import { Link } from 'react-router-dom';
import { Bar, BarChart, CartesianGrid, Cell, ResponsiveContainer, Tooltip, XAxis, YAxis } from 'recharts';
import { useWarehousesQuery } from '../api/inventory';
import { useAlertsQuery, useOverviewQuery, usePendingQuery, usePoFunnelQuery, useStockByValueQuery } from '../api/insights';
import { usePoActionMutation, usePurchaseOrdersQuery } from '../api/procurement';
import { useRecoveryActionMutation, useRedistributionActionMutation } from '../api/modules';
import { useTransferActionMutation } from '../api/inventory';
import { useAppDispatch, useAppSelector } from '../app/store';
import Badge from '../components/Badge';
import DataTable from '../components/DataTable';
import QueryState from '../components/QueryState';
import StatCard from '../components/StatCard';
import DnaCards from '../components/dna/DnaCards';
import SupplierPOActions from '../components/po/SupplierPOActions';
import { setSelectedWarehouse } from '../features/auth/authSlice';
import { useAction } from '../hooks/useAction';
import { useAuth } from '../hooks/useAuth';
import type { PurchaseOrder } from '../types';
import { date, dateTime, humanize, number, rupees } from '../utils/format';

function SupplierDashboard() {
  const { user } = useAuth();
  const q = usePurchaseOrdersQuery({ limit: 100 });
  const open = (q.data?.items ?? []).filter((p) => ['approved', 'confirmed', 'dispatched', 'partially_received'].includes(p.status));
  return (
    <>
      <div className="page-head">
        <div>
          <h1>Welcome, {user?.supplier?.name ?? user?.name}</h1>
          <p>Purchase orders from Smart Inventory. Confirm quantities and dates, then record dispatch.</p>
        </div>
        <Link to="/purchase-orders" className="btn">
          All purchase orders
        </Link>
      </div>
      <div className="stats">
        <StatCard label="Awaiting confirmation" value={(q.data?.items ?? []).filter((p) => p.status === 'approved').length} loading={q.isLoading} tone="warning" />
        <StatCard label="Confirmed, not dispatched" value={(q.data?.items ?? []).filter((p) => p.status === 'confirmed').length} loading={q.isLoading} />
        <StatCard label="In transit" value={(q.data?.items ?? []).filter((p) => p.status === 'dispatched').length} loading={q.isLoading} />
        <StatCard label="Delivered" value={(q.data?.items ?? []).filter((p) => p.status === 'received').length} loading={q.isLoading} tone="success" />
      </div>
      <div className="card">
        <div className="card-head">
          <h2>Open orders</h2>
        </div>
        <DataTable<PurchaseOrder>
          rows={open}
          loading={q.isLoading}
          error={q.error}
          onRetry={q.refetch}
          rowKey={(p) => p._id}
          empty="No open purchase orders"
          columns={[
            { key: 'po', header: 'PO no.', render: (p) => <strong>{p.poNumber}</strong>, sortValue: (p) => p.poNumber },
            { key: 'wh', header: 'Deliver to', render: (p) => p.warehouse.name },
            { key: 'status', header: 'Status', render: (p) => <Badge status={p.status} /> },
            { key: 'lines', header: 'Lines', render: (p) => p.items.map((i) => `${i.product.sku} × ${i.quantityOrdered}`).join(', ') },
            { key: 'total', header: 'Total', align: 'right', render: (p) => rupees(p.totalCost), sortValue: (p) => p.totalCost },
            { key: 'exp', header: 'Expected', render: (p) => date(p.expectedDeliveryDate), sortValue: (p) => p.expectedDeliveryDate ?? '' },
            { key: 'actions', header: 'Actions', render: (p) => <SupplierPOActions po={p} /> },
          ]}
        />
      </div>
    </>
  );
}

function PendingApprovals() {
  const { is } = useAuth();
  const isAdmin = is('admin');
  const q = usePendingQuery();
  const [poAction] = usePoActionMutation();
  const [recoveryAction] = useRecoveryActionMutation();
  const [redistAction] = useRedistributionActionMutation();
  const [transferAction] = useTransferActionMutation();
  const { busy, run } = useAction();
  const d = q.data;
  const total = d ? d.purchaseOrders.length + d.recoveryPlans.length + d.redistributionPlans.length + d.transfers.length : 0;
  return (
    <div className="card">
      <div className="card-head">
        <h2>Pending approvals</h2>
        <span className="badge badge-warning">{total}</span>
      </div>
      <QueryState loading={q.isLoading} error={q.error} onRetry={q.refetch} isEmpty={total === 0} empty="Nothing is waiting for approval">
        <ul className="plain-list">
          {d?.purchaseOrders.map((p) => (
            <li key={p._id} className="row spread gap">
              <span>
                <Link to={`/purchase-orders?focus=${p._id}`}>{p.poNumber}</Link> · {p.supplier.name} · {rupees(p.totalCost)} {p.autoGenerated && <Badge tone="navy">Auto</Badge>}
              </span>
              {isAdmin && (<button type="button" className="btn btn-sm btn-primary" disabled={busy === p._id} onClick={() => run(p._id, () => poAction({ id: p._id, action: 'approve' }).unwrap(), `${p.poNumber} approved`)}>
                {busy === p._id ? 'Saving...' : 'Approve'}
              </button>)}
            </li>
          ))}
          {d?.recoveryPlans.map((p) => (
            <li key={p._id} className="row spread gap">
              <span>
                <Link to={`/recovery/${p._id}`}>{p.planNo}</Link> · recovery for {p.product.sku} at {p.targetWarehouse.name}
                {p.option && ` · ${rupees(p.option.totalCost)}`}
              </span>
              {isAdmin && (<button type="button" className="btn btn-sm btn-primary" disabled={busy === p._id} onClick={() => run(p._id, () => recoveryAction({ id: p._id, action: 'approve' }).unwrap(), `${p.planNo} approved`)}>
                {busy === p._id ? 'Saving...' : 'Approve'}
              </button>)}
            </li>
          ))}
          {d?.redistributionPlans.map((p) => (
            <li key={p._id} className="row spread gap">
              <span>
                <Link to={`/redistribution?plan=${p._id}`}>{p.planNo}</Link> · move {p.units} {p.product.sku} from {p.sourceWarehouse.name}
              </span>
              {isAdmin && (<button type="button" className="btn btn-sm btn-primary" disabled={busy === p._id} onClick={() => run(p._id, () => redistAction({ id: p._id, action: 'approve' }).unwrap(), `${p.planNo} approved`)}>
                {busy === p._id ? 'Saving...' : 'Approve'}
              </button>)}
            </li>
          ))}
          {d?.transfers.map((t) => (
            <li key={t._id} className="row spread gap">
              <span>
                <Link to="/transfers">Transfer</Link> · {t.quantity} {t.product.sku} {t.fromWarehouse.code} → {t.toWarehouse.code}
              </span>
              {isAdmin && (<button type="button" className="btn btn-sm btn-primary" disabled={busy === t._id} onClick={() => run(t._id, () => transferAction({ id: t._id, action: 'approve' }).unwrap(), 'Transfer approved')}>
                {busy === t._id ? 'Saving...' : 'Approve'}
              </button>)}
            </li>
          ))}
        </ul>
      </QueryState>
    </div>
  );
}

const FUNNEL_COLORS: Record<string, string> = {
  pending_approval: '#d99a15',
  approved: '#26365b',
  confirmed: '#3c5a99',
  dispatched: '#1f5fa8',
  partially_received: '#b07a1a',
  received: '#1e7a46',
  rejected: '#b42318',
  cancelled: '#9aa1ab',
  draft: '#c7c2b8',
};

export default function Dashboard() {
  const { user, is } = useAuth();
  const selected = useAppSelector((s) => s.auth.selectedWarehouse);
  const dispatch = useAppDispatch();
  const status = useAppSelector((s) => s.realtime.status);
  const lastEventAt = useAppSelector((s) => s.realtime.lastEventAt);
  const warehouses = useWarehousesQuery(undefined, { skip: is('supplier') });
  const params = { warehouse: selected || undefined };
  const skip = is('supplier');
  const overview = useOverviewQuery(params, { skip });
  const byValue = useStockByValueQuery(params, { skip });
  const funnel = usePoFunnelQuery(params, { skip });
  const alerts = useAlertsQuery({ resolved: 'false', warehouse: selected || undefined, limit: 8 }, { skip });

  if (is('supplier')) return <SupplierDashboard />;
  const o = overview.data;
  const canFilter = user?.role === 'admin';
  return (
    <>
      <div className="page-head">
        <div>
          <h1>Dashboard</h1>
          <p>
            <span className={`live-dot ${status}`} aria-hidden /> {status === 'connected' ? 'Live' : 'Not live'}
            {lastEventAt ? ` · last update ${dateTime(lastEventAt)}` : ''}
          </p>
        </div>
        <label className="field" style={{ marginBottom: 0, minWidth: 220 }}>
          <span className="sr-only">Warehouse filter</span>
          <select
            aria-label="Warehouse filter"
            value={selected}
            disabled={!canFilter}
            onChange={(e) => dispatch(setSelectedWarehouse(e.target.value))}
          >
            <option value="">All warehouses</option>
            {warehouses.data?.items.map((w) => (
              <option key={w._id} value={w._id}>
                {w.code} · {w.name}
              </option>
            ))}
          </select>
        </label>
      </div>
      {overview.error ? (
        <QueryState error={overview.error} onRetry={overview.refetch} />
      ) : (
        <div className="stats">
          <StatCard label="Products" value={number(o?.products, 0)} loading={overview.isLoading} to="/products" />
          <StatCard label="Warehouses" value={number(o?.warehouses, 0)} loading={overview.isLoading} to="/warehouses" />
          <StatCard label="Suppliers" value={number(o?.suppliers, 0)} loading={overview.isLoading} to={is('admin', 'warehouse_manager') ? '/suppliers' : undefined} />
          <StatCard label="Open alerts" value={number(o?.openAlerts, 0)} loading={overview.isLoading} tone={o && o.openAlerts > 0 ? 'warning' : undefined} to="/alerts" />
          <StatCard label="Pending POs" value={number(o?.pendingPOs, 0)} loading={overview.isLoading} to="/purchase-orders" />
          <StatCard label="Low-stock lines" value={number(o?.lowStockLines, 0)} loading={overview.isLoading} tone={o && o.lowStockLines > 0 ? 'danger' : undefined} to="/alerts" />
          <StatCard label="Total units" value={number(o?.totalUnits, 0)} loading={overview.isLoading} to="/stock" />
          <StatCard label="Stock value" value={rupees(o?.stockValue, true)} loading={overview.isLoading} />
        </div>
      )}
      <DnaCards />
      <div className="grid grid-2">
        <div className="card">
          <div className="card-head">
            <h2>Top products by stock value</h2>
          </div>
          <QueryState loading={byValue.isLoading} error={byValue.error} onRetry={byValue.refetch} isEmpty={!byValue.data?.items.length} empty="No stock yet">
            <div style={{ width: '100%', height: 300 }}>
              <ResponsiveContainer>
                <BarChart data={byValue.data?.items} layout="vertical" margin={{ left: 10, right: 20 }}>
                  <CartesianGrid strokeDasharray="3 3" horizontal={false} />
                  <XAxis type="number" tickFormatter={(v) => `₹${(v / 1000).toFixed(0)}k`} fontSize={11} />
                  <YAxis type="category" dataKey="sku" width={100} fontSize={11} />
                  <Tooltip formatter={(v: number) => rupees(v)} labelFormatter={(l) => byValue.data?.items.find((i) => i.sku === l)?.name ?? l} />
                  <Bar dataKey="value" name="Stock value" fill="#8c1d2f" radius={[0, 4, 4, 0]} />
                </BarChart>
              </ResponsiveContainer>
            </div>
          </QueryState>
        </div>
        <div className="card">
          <div className="card-head">
            <h2>Purchase order funnel</h2>
          </div>
          <QueryState loading={funnel.isLoading} error={funnel.error} onRetry={funnel.refetch} isEmpty={!funnel.data?.items.some((i) => i.count > 0)} empty="No purchase orders yet">
            <div style={{ width: '100%', height: 300 }}>
              <ResponsiveContainer>
                <BarChart data={funnel.data?.items.map((i) => ({ ...i, label: humanize(i.status) }))}>
                  <CartesianGrid strokeDasharray="3 3" vertical={false} />
                  <XAxis dataKey="label" fontSize={10} interval={0} angle={-25} textAnchor="end" height={60} />
                  <YAxis allowDecimals={false} fontSize={11} />
                  <Tooltip />
                  <Bar dataKey="count" name="Purchase orders" radius={[4, 4, 0, 0]}>
                    {funnel.data?.items.map((i) => (
                      <Cell key={i.status} fill={FUNNEL_COLORS[i.status] ?? '#26365b'} />
                    ))}
                  </Bar>
                </BarChart>
              </ResponsiveContainer>
            </div>
          </QueryState>
        </div>
        <div className="card">
          <div className="card-head">
            <h2>Recent alerts</h2>
            <Link to="/alerts" className="btn btn-sm">
              All alerts
            </Link>
          </div>
          <QueryState loading={alerts.isLoading} error={alerts.error} onRetry={alerts.refetch} isEmpty={!alerts.data?.items.length} empty="No open alerts">
            <ul className="plain-list">
              {alerts.data?.items.map((a) => (
                <li key={a._id}>
                  <Badge status={a.severity} /> <Badge tone="default">{humanize(a.type)}</Badge>{' '}
                  {a.purchaseOrder ? (
                    <Link to={`/purchase-orders?focus=${a.purchaseOrder._id}`}>{a.message}</Link>
                  ) : a.product ? (
                    <Link to={`/stock?product=${a.product._id}`}>{a.message}</Link>
                  ) : (
                    <Link to="/alerts">{a.message}</Link>
                  )}
                  <div className="muted small">{dateTime(a.createdAt)}</div>
                </li>
              ))}
            </ul>
          </QueryState>
        </div>
        {is('admin', 'warehouse_manager') && <PendingApprovals />}
      </div>
    </>
  );
}
